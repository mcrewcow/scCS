"""Genuine splicing inputs for the public-data PairScorer tutorials.

LARRY counts were generated by the data providers using dropEst/velocyto.
Exporting those counts to loom changes storage format, not their measurement.
"""

from __future__ import annotations

import json
from pathlib import Path

import anndata as ad
import h5py
import numpy as np
import pandas as pd
from scipy import sparse

from .data import fetch, SOURCES


def audit_counts(adata):
    """Require aligned, nonnegative integer-valued spliced/unspliced counts."""
    if not adata.obs_names.is_unique or not adata.var_names.is_unique:
        raise ValueError("Cell and gene identifiers must be unique before loom export.")
    rows = []
    for name in ("spliced", "unspliced"):
        if name not in adata.layers:
            raise ValueError(f"Missing genuine {name!r} count layer.")
        matrix = adata.layers[name]
        values = matrix.data if sparse.issparse(matrix) else np.asarray(matrix).ravel()
        if matrix.shape != adata.shape or not np.isfinite(values).all():
            raise ValueError(f"Invalid shape or nonfinite counts in {name}.")
        if (values < 0).any() or not np.allclose(values, np.rint(values), atol=1e-6, rtol=0):
            raise ValueError(f"{name} must contain nonnegative raw molecule counts.")
        total = float(matrix.sum())
        if total <= 0:
            raise ValueError(f"{name} has no measured counts.")
        rows.append(
            {
                "layer": name,
                "cells": adata.n_obs,
                "genes": adata.n_vars,
                "total_counts": total,
                "nonzero_entries": int(np.count_nonzero(values)),
            }
        )
    return pd.DataFrame(rows)


def write_verified_loom(adata, path):
    """Export real counts and verify their exact alignment after reading loom."""
    import loompy

    audit_counts(adata)
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists():
        attrs = {"CellID": adata.obs_names.to_numpy(dtype=str)}
        for column in adata.obs:
            attrs[column] = adata.obs[column].astype(str).to_numpy()
        layers = {"": sparse.csc_matrix(adata.layers["spliced"].T)}
        layers.update(
            {name: sparse.csc_matrix(adata.layers[name].T) for name in ("spliced", "unspliced")}
        )
        temporary = path.with_name(path.stem + ".partial.loom")
        temporary.unlink(missing_ok=True)
        try:
            loompy.create(
                str(temporary), layers, {"Gene": adata.var_names.to_numpy(dtype=str)}, attrs
            )
            temporary.replace(path)
        finally:
            temporary.unlink(missing_ok=True)
    reread = ad.read_loom(path, obs_names="CellID", var_names="Gene", sparse=True)
    if not reread.obs_names.equals(adata.obs_names) or not reread.var_names.equals(adata.var_names):
        raise ValueError("Cached loom has different cell/gene identifiers; remove it and retry.")
    for name in ("spliced", "unspliced"):
        if (sparse.csr_matrix(reread.layers[name]) != sparse.csr_matrix(adata.layers[name])).nnz:
            raise ValueError("Loom counts differ from the source; remove it and retry.")
    return path


def load_larry_counts(directory, *, max_per_stratum=600, n_genes=2000, seed=19):
    """Read day-2/day-4 LSK counts with an explicit teaching-size sampling cap.

    The cap is per source state and time point. Full eligible composition is
    returned separately; capped counts must never be used as biological abundance.
    No clone-derived fate scores or expression-only transition graphs are loaded.
    """
    if max_per_stratum is not None and max_per_stratum < 1:
        raise ValueError("max_per_stratum must be positive or None.")
    if n_genes < 1:
        raise ValueError("n_genes must be positive.")
    path = fetch("larry_velocity", directory)
    with h5py.File(path) as handle:
        obs = ad.io.read_elem(handle["obs"])
        var = ad.io.read_elem(handle["var"])
        eligible = obs.time_info.isin([2, 4]) & obs["Starting population"].eq("Lin-Kit+Sca1+")
        obs = obs.loc[eligible].copy()
        composition = pd.crosstab(obs.state_info, obs.time_info)
        rng = np.random.default_rng(seed)
        selected = []
        for _, group in obs.groupby(["time_info", "state_info"], observed=True, sort=True):
            indices = np.asarray(group.index)
            if max_per_stratum is not None and len(indices) > max_per_stratum:
                indices = rng.choice(indices, max_per_stratum, replace=False)
            selected.extend(indices)
        source_ids = ad.io.read_elem(handle["obs"]).index
        positions = np.sort(source_ids.get_indexer(selected))
        obs = ad.io.read_elem(handle["obs"]).iloc[positions].copy()
        spliced = sparse.csr_matrix(ad.io.sparse_dataset(handle["layers/spliced"])[positions])
        unspliced = sparse.csr_matrix(ad.io.sparse_dataset(handle["layers/unspliced"])[positions])
    # A reproducible count-variability screen, before standard scVelo processing.
    mean = np.asarray(spliced.mean(0)).ravel()
    variance = np.asarray(spliced.astype(float).power(2).mean(0)).ravel() - mean**2
    covered = (np.asarray(spliced.sum(0)).ravel() >= 20) & (
        np.asarray(unspliced.sum(0)).ravel() >= 10
    )
    rank = np.argsort(np.where(covered, variance / (mean + 1), -np.inf))[-n_genes:]
    markers = var.index.isin(["Kit", "Cd34", "Gata2", "Elane", "Mpo", "Csf1r", "Lyz2", "S100a8"])
    keep = np.sort(np.union1d(rank, np.flatnonzero(markers)))
    spliced, unspliced = spliced[:, keep], unspliced[:, keep]
    obs["source_state"] = obs.state_info.astype(str)
    obs["condition"] = "day" + obs.time_info.astype(int).astype(str)
    obs["culture_series"] = "LARRY_LSK_series"
    a = ad.AnnData(spliced.copy(), obs=obs, var=var.iloc[keep].copy())
    a.var_names_make_unique()
    a.layers["spliced"], a.layers["unspliced"] = spliced, unspliced
    audit_counts(a)
    manifest = {
        "source": SOURCES["larry_velocity"][0],
        "source_md5": SOURCES["larry_velocity"][3],
        "starting_population": "Lin-Kit+Sca1+",
        "days": [2, 4],
        "max_per_state_time": max_per_stratum,
        "requested_genes": n_genes,
        "seed": seed,
        "eligible_cells": int(eligible.sum()),
        "loaded_cells": a.n_obs,
        "clone_information_used_for_model": False,
    }
    a.uns["count_provenance"] = json.dumps(manifest, sort_keys=True)
    return a, composition, manifest
